function current_lang(): string
{
    $l = $_SESSION['lang'] ?? $_COOKIE['trd_lang'] ?? 'en';
    return $l === 'ar' ? 'ar' : 'en';
}

function lang_boot(): void
{
    $fromQ = $_GET['lang'] ?? '';
    if ($fromQ === 'ar' || $fromQ === 'en') {
        $_SESSION['lang'] = $fromQ;
        $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || ((int)($_SERVER['SERVER_PORT'] ?? 0) === 443);
        setcookie('trd_lang', $fromQ, [
            'expires' => time() + 86400 * 400,
            'path' => '/',
            'secure' => $https,
            'httponly' => false,
            'samesite' => 'Lax',
        ]);
        $uri = $_SERVER['REQUEST_URI'] ?? '/';
        $parts = parse_url($uri);
        parse_str($parts['query'] ?? '', $qs);
        unset($qs['lang']);
        $path = $parts['path'] ?? '/';
        $next = $path . ($qs ? ('?' . http_build_query($qs)) : '');
        header('Location: ' . $next);
        exit;
    }
    if (empty($_SESSION['lang']) && empty($_COOKIE['trd_lang'])) {
        $al = strtolower((string)($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? ''));
        if (str_starts_with($al, 'ar')) {
            $_SESSION['lang'] = 'ar';
        }
    }
}

function t(string $key, array $vars = [], ?string $fallback = null): string
{
    $dict = trd_i18n_dict();
    $lang = current_lang();
    $s = $dict[$lang][$key] ?? $dict['en'][$key] ?? ($fallback ?? $key);
    foreach ($vars as $k => $v) {
        $s = str_replace('{' . $k . '}', (string)$v, $s);
    }
    return $s;
}

function lang_dir(): string
{
    return current_lang() === 'ar' ? 'rtl' : 'ltr';
}

function city_label(?string $name, ?string $gov = null): string
{
    if (!$name) {
        return t('common.cityPending');
    }
    $n = t('city.' . $name, [], $name);
    if (!$gov) {
        return $n;
    }
    $g = t('gov.' . $gov, [], $gov);
    return ($g && $g !== $n) ? ($n . ' · ' . $g) : $n;
}

function lang_switch_html(bool $compact = true): string
{
    $lang = current_lang();
    $cls = 'lang-switch' . ($compact ? ' is-compact' : '');
    $enOn = $lang === 'en' ? ' is-on' : '';
    $arOn = $lang === 'ar' ? ' is-on' : '';
    $here = $_SERVER['REQUEST_URI'] ?? '/';
    $parts = parse_url($here);
    parse_str($parts['query'] ?? '', $qs);
    $path = $parts['path'] ?? '/';
    $qsEn = $qs; $qsEn['lang'] = 'en';
    $qsAr = $qs; $qsAr['lang'] = 'ar';
    $enUrl = $path . '?' . http_build_query($qsEn);
    $arUrl = $path . '?' . http_build_query($qsAr);
    return '<div class="' . $cls . '" role="group" aria-label="' . e(t('lang.switch')) . '">'
        . '<a class="lang-btn' . $enOn . '" href="' . e($enUrl) . '">EN</a>'
        . '<a class="lang-btn' . $arOn . '" href="' . e($arUrl) . '">ع</a>'
        . '</div>';
}
